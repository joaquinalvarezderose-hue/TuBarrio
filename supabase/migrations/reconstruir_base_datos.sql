-- ============================================================
-- Reconstrucción completa de la base de datos TuBarrio
-- ============================================================

-- 1. Tabla perfiles (fundamental)
CREATE TABLE IF NOT EXISTS public.perfiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT UNIQUE NOT NULL,
  nombre_completo TEXT,
  whatsapp TEXT,
  rol TEXT DEFAULT 'jugador',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabla torneos
CREATE TABLE IF NOT EXISTS public.torneos (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  titulo TEXT NOT NULL,
  subtitulo TEXT,
  fecha_inicio DATE,
  fecha_fin DATE,
  imagen_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla torneo_estado
CREATE TABLE IF NOT EXISTS public.torneo_estado (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  torneo_id BIGINT UNIQUE NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  estado TEXT DEFAULT 'inscripciones_abiertas',
  current_participantes INTEGER DEFAULT 0,
  max_participantes_total INTEGER,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabla inscripciones_torneo
CREATE TABLE IF NOT EXISTS public.inscripciones_torneo (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id),
  perfil_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  estado TEXT NOT NULL DEFAULT 'pendiente_revision'
    CHECK (estado IN ('pendiente_revision', 'pagado_aprobado', 'rechazado')),
  monto NUMERIC(10,2) NOT NULL,
  moneda TEXT NOT NULL DEFAULT 'ARS',
  metodo_pago TEXT NOT NULL DEFAULT 'transferencia_alias',
  categoria TEXT,
  grupo TEXT,
  alias_destino TEXT NOT NULL,
  whatsapp_destino TEXT NOT NULL,
  referencia_manual TEXT,
  comprobante_url TEXT,
  aprobado_por UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  aprobado_en TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_inscripcion_torneo_perfil UNIQUE (torneo_id, perfil_id)
);

-- 5. Tabla torneo_jugadores
CREATE TABLE IF NOT EXISTS public.torneo_jugadores (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  perfil_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  categoria TEXT,
  grupo TEXT,
  puntos INTEGER DEFAULT 0,
  partidos_jugados INTEGER DEFAULT 0,
  sets_ganados INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT uq_torneo_jugador UNIQUE (torneo_id, perfil_id)
);

-- 6. Tabla partidos
CREATE TABLE IF NOT EXISTS public.partidos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  jugador1_id UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  jugador2_id UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  jornada INTEGER,
  ronda INTEGER,
  bracket_tipo TEXT, -- 'round_robin', 'eliminacion_directa', 'grupo'
  estado TEXT DEFAULT 'programado',
  resultado_jugador1 INTEGER,
  resultado_jugador2 INTEGER,
  sets_jugador1 INTEGER DEFAULT 0,
  sets_jugador2 INTEGER DEFAULT 0,
  ganador_id UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha_programada TIMESTAMPTZ,
  confirmado_por UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  siguiente_partido_id UUID REFERENCES public.partidos(id) ON DELETE SET NULL,
  external_match_key TEXT,
  stage_name TEXT, -- Para nombres de etapas: 'Final', 'Semifinal', etc.
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Tabla torneo_grupos
CREATE TABLE IF NOT EXISTS public.torneo_grupos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  codigo TEXT,
  nombre TEXT,
  categoria TEXT,
  grupo_base_id UUID REFERENCES public.torneo_grupos(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Tabla torneo_configuracion
CREATE TABLE IF NOT EXISTS public.torneo_configuracion (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  categoria TEXT,
  formato TEXT DEFAULT 'round_robin',
  max_participantes_por_grupo INTEGER DEFAULT 4,
  numero_grupos INTEGER,
  min_participantes_por_grupo INTEGER,
  max_participantes_total INTEGER,
  clasificados_por_grupo INTEGER NOT NULL DEFAULT 2,
  crear_playoffs_eliminacion_directa BOOLEAN NOT NULL DEFAULT false,
  grupo_base TEXT,
  partidos_por_jugador INTEGER DEFAULT 3,
  grupo_base_id UUID REFERENCES public.torneo_grupos(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Tabla torneo_propuestas_partido
CREATE TABLE IF NOT EXISTS public.torneo_propuestas_partido (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  partido_id UUID REFERENCES public.partidos(id) ON DELETE CASCADE,
  jugador1_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  jugador2_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  fecha_propuesta TIMESTAMPTZ NOT NULL,
  estado TEXT DEFAULT 'pendiente',
  propuesta_por UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  respuesta_por UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  debe_confirmar_por UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha_respuesta TIMESTAMPTZ,
  mensaje_propuesta TEXT,
  mensaje_respuesta TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT uq_propuesta_pair UNIQUE (torneo_id, jugador1_id, jugador2_id, estado)
);

-- 10. Tabla torneo_partidos_historial
CREATE TABLE IF NOT EXISTS public.torneo_partidos_historial (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  partido_id UUID NOT NULL REFERENCES public.partidos(id) ON DELETE CASCADE,
  torneo_id BIGINT NOT NULL REFERENCES public.torneos(id) ON DELETE CASCADE,
  jugador1_id UUID NOT NULL REFERENCES public.perfiles(id),
  jugador2_id UUID NOT NULL REFERENCES public.perfiles(id),
  resultado_jugador1 INTEGER,
  resultado_jugador2 INTEGER,
  sets_jugador1 INTEGER DEFAULT 0,
  sets_jugador2 INTEGER DEFAULT 0,
  ganador_id UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha_registro TIMESTAMPTZ DEFAULT NOW(),
  registrado_por UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  external_match_key TEXT,
  CONSTRAINT uq_partido_historial UNIQUE (partido_id)
);

-- 11. Tabla marketplace_servicios
CREATE TABLE IF NOT EXISTS public.marketplace_servicios (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  titulo TEXT NOT NULL,
  descripcion TEXT,
  precio NUMERIC(10,2),
  categoria TEXT,
  proveedor_id UUID REFERENCES public.perfiles(id) ON DELETE SET NULL,
  contacto_whatsapp TEXT,
  contacto_email TEXT,
  imagen_url TEXT,
  estado TEXT DEFAULT 'activo',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índices importantes
CREATE INDEX IF NOT EXISTS idx_perfiles_email ON public.perfiles(email);
