-- Políticas RLS básicas
CREATE POLICY "Perfiles select para todos" ON public.perfiles FOR SELECT USING (true);
CREATE POLICY "Perfiles update propio" ON public.perfiles FOR UPDATE USING (id = auth.uid());
CREATE POLICY "Torneos select para todos" ON public.torneos FOR SELECT USING (true);
CREATE POLICY "Partidos select para todos" ON public.partidos FOR SELECT USING (true);
CREATE POLICY "Torneo jugadores select para participantes" ON public.torneo_jugadores FOR SELECT USING (torneo_id IN (SELECT torneo_id FROM public.torneo_jugadores WHERE perfil_id = auth.uid()));

-- Función auxiliar para actualizar timestamps
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Triggers para updated_at
CREATE TRIGGER trigger_perfiles_updated_at
  BEFORE UPDATE ON public.perfiles
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER trigger_torneos_updated_at
  BEFORE UPDATE ON public.torneos
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER trigger_partidos_updated_at
  BEFORE UPDATE ON public.partidos
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER trigger_inscripciones_updated_at
  BEFORE UPDATE ON public.inscripciones_torneo
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

