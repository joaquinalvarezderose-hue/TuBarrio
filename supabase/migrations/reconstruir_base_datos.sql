CREATE INDEX IF NOT EXISTS idx_torneo_estado_torneo ON public.torneo_estado(torneo_id);
CREATE INDEX IF NOT EXISTS idx_inscripciones_perfil ON public.inscripciones_torneo(perfil_id);
CREATE INDEX IF NOT EXISTS idx_inscripciones_torneo ON public.inscripciones_torneo(torneo_id);
CREATE INDEX IF NOT EXISTS idx_inscripciones_estado ON public.inscripciones_torneo(estado);
CREATE INDEX IF NOT EXISTS idx_torneo_jugadores_torneo ON public.torneo_jugadores(torneo_id);
CREATE INDEX IF NOT EXISTS idx_torneo_jugadores_perfil ON public.torneo_jugadores(perfil_id);
CREATE INDEX IF NOT EXISTS idx_partidos_torneo ON public.partidos(torneo_id);
CREATE INDEX IF NOT EXISTS idx_partidos_jugadores ON public.partidos(jugador1_id, jugador2_id);
